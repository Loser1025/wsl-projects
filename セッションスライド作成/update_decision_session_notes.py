def get_slides_service():
    creds = service_account.Credentials.from_service_account_file(SA_FILE, scopes=SCOPES)
    return build("slides", "v1", credentials=creds)


def get_presentation_slides(service):
    presentation = service.presentations().get(
        presentationId=PRESENTATION_ID
    ).execute()
    return presentation.get("slides", [])


def update_speaker_notes(service, slides):
    requests = []

    for idx, slide in enumerate(slides):
        if idx not in SPEAKER_NOTES:
            continue

        new_note_text = SPEAKER_NOTES[idx]
        notes_page = slide.get("slideProperties", {}).get("notesPage")
        if not notes_page:
            print(f"スライド{idx+1}: ノートページなし、スキップ")
            continue

        notes_text_element = None
        for element in notes_page.get("pageElements", []):
            shape = element.get("shape", {})
            placeholder = shape.get("placeholder", {})
            if placeholder.get("type") == "BODY":
                notes_text_element = element
                break

        if not notes_text_element:
            print(f"スライド{idx+1}: ノートテキスト要素なし、スキップ")
            continue

        element_id = notes_text_element["objectId"]

        # 既存テキストの内容とインデックスを取得
        text_content = notes_text_element.get("shape", {}).get("text", {})
        existing_text = ""
        for te in text_content.get("textElements", []):
            tr = te.get("textRun", {})
            existing_text += tr.get("content", "")

        end_index = sum(
            len(te.get("textRun", {}).get("content", ""))
            for te in text_content.get("textElements", [])
        )
        # API は末尾の改行の後に挿入できないため、1つ前に挿入する
        if end_index > 0:
            end_index -= 1

        existing_text = existing_text.strip()
        if existing_text:
            insert_text = f"\n\n---【文字起こしより】---\n{new_note_text}"
        else:
            insert_text = new_note_text

        requests.append({
            "insertText": {
                "objectId": element_id,
                "insertionIndex": end_index,
                "text": insert_text
            }
        })

        print(f"スライド{idx+1}: ノート追記準備完了")

    if requests:
        response = service.presentations().batchUpdate(
            presentationId=PRESENTATION_ID,
            body={"requests": requests}
        ).execute()
        print(f"\n完了: {len(requests)}枚のスライドを更新しました")
    else:
        print("更新するスライドがありませんでした")


def main():
    print("決断セッション スピーカーノート追記ツール")
    print(f"プレゼンテーションID: {PRESENTATION_ID}\n")

    service = get_slides_service()
    slides = get_presentation_slides(service)
    print(f"スライド数: {len(slides)}枚\n")

    update_speaker_notes(service, slides)


if __name__ == "__main__":
    main()
